def text_width(text, scale=1, spacing=1):
    w = 0
    for i, ch in enumerate(text.upper()):
        g = FONT.get(ch, FONT[' '])
        w += len(g[0]) * scale
        if i < len(text) - 1:
            w += spacing * scale
    return w


def text_pixels(text, scale=1, spacing=1):
    """Yield (u, v) pixel coordinates; u to the right from 0, v up from 0 (bottom row)."""
    u0 = 0
    for ch in text.upper():
        g = FONT.get(ch, FONT[' '])
        rows = len(g)
        for r, row in enumerate(g):
            for c, bit in enumerate(row):
                if bit == '1':
                    for sx in range(scale):
                        for sy in range(scale):
                            yield u0 + c * scale + sx, (rows - 1 - r) * scale + sy
        u0 += (len(g[0]) + spacing) * scale


def giant_text(w, text, x, y, z, facing='south', block='white_concrete', scale=1, depth=1, center=True,
               back=None, outline=None):
    """Write text in a vertical plane. facing = direction the readable side faces.

    (x, y, z) is the bottom-center (center=True) or bottom-left (as seen by the reader) of the text.
    """
    # reader looks opposite to facing; reader's right direction:
    right = {'south': (1, 0), 'north': (-1, 0), 'east': (0, -1), 'west': (0, 1)}[facing]
    back_dir = {'south': (0, -1), 'north': (0, 1), 'east': (-1, 0), 'west': (1, 0)}[facing]
    wdt = text_width(text, scale)
    u_off = -(wdt // 2) if center else 0
    pix = set(text_pixels(text, scale))
    for (u, v) in pix:
        for d in range(depth):
            px = x + right[0] * (u + u_off) + back_dir[0] * d
            pz = z + right[1] * (u + u_off) + back_dir[1] * d
            w.set(px, y + v, pz, block)
    if back:
        for (u, v) in pix:
            px = x + right[0] * (u + u_off) + back_dir[0] * depth
            pz = z + right[1] * (u + u_off) + back_dir[1] * depth
            w.set(px, y + v, pz, back)
    return wdt
