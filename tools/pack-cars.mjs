// Packs the Blender cars for the web build. Builds each car's GLB (one LOD)
// with blender/build_car.py, compresses it with gltfpack (meshopt and
// quantized vertices: about 130 KB a car) into src/vehicles/models/, and
// writes the index with each car's style (the colours and finishes the
// Unity build reads from Resources/Cars/<id>.style.json).
//   node tools/pack-cars.mjs [--from DIR] [--python PY] [--gltfpack BIN] [--lod N]
//   --from DIR: GLBs already built (skips Blender)
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const arg = (name, def) => {
  const i = process.argv.indexOf(name);
  return i >= 0 ? process.argv[i + 1] : def;
};
const python = arg('--python', fs.existsSync('/root/bpy-venv/bin/python') ? '/root/bpy-venv/bin/python' : 'python3');
const lod = arg('--lod', '1');
let from = arg('--from', '');
const out = path.join(root, 'src/vehicles/models');
const styles = path.join(root, 'unity/Assets/Halcyon/Art/Resources/Cars');

if (!from) {
  from = fs.mkdtempSync(path.join(os.tmpdir(), 'halcyon-cars-'));
  console.log(`building every car in Blender into ${from} (about a minute a car)`);
  execFileSync(python, [path.join(root, 'blender/build_car.py'), '--', '--car', 'all', '--glb', from, '--glb-lod', lod, '--no-fbx'], { stdio: ['ignore', 'ignore', 'inherit'] });
}
const gltfpack = arg('--gltfpack', '');
const pack = (input, output) => {
  const opts = ['-i', input, '-o', output, '-cc', '-kn', '-km'];
  if (gltfpack) execFileSync(gltfpack, opts, { stdio: 'inherit' });
  else execFileSync('npx', ['--yes', 'gltfpack@1.3.0', ...opts], { stdio: 'inherit' });
};

fs.mkdirSync(out, { recursive: true });
const ids = fs.readdirSync(from).filter((f) => f.endsWith('.glb')).map((f) => f.slice(0, -4)).sort();
const entries = [];
let total = 0;
for (const id of ids) {
  const style = JSON.parse(fs.readFileSync(path.join(styles, `${id}.style.json`), 'utf8'));
  const dst = path.join(out, `${id}.glb`);
  pack(path.join(from, `${id}.glb`), dst);
  const size = fs.statSync(dst).size;
  total += size;
  console.log(`${id.padEnd(26)} ${(size / 1024).toFixed(0)} KB`);
  entries.push({ id, style });
}
const ident = (id) => id.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase()).replace(/^[0-9]/, '_$&');
const lines = [
  '// Generated by tools/pack-cars.mjs: the Blender cars (blender/build_car.py, LOD ' + lod + '),',
  '// packed with gltfpack, and their styles from Resources/Cars/<id>.style.json.',
  "import type { CarStyle } from '../render/car-style';",
  ...entries.map((e) => `import ${ident(e.id)} from './${e.id}.glb';`),
  '',
  'export const CAR_MODELS: Record<string, { glb: Uint8Array; style: CarStyle }> = {',
  ...entries.map((e) => {
    const { id, name, ...rest } = e.style;
    void id;
    void name;
    return `  '${e.id}': { glb: ${ident(e.id)}, style: ${JSON.stringify(rest).replace(/"([a-zA-Z]+)":/g, '$1: ').replace(/,/g, ', ').replace(/^\{/, '{ ').replace(/\}$/, ' }')} },`;
  }),
  '};',
  '',
];
fs.writeFileSync(path.join(out, 'index.ts'), lines.join('\n'));
console.log(`${entries.length} cars, ${(total / 1024).toFixed(0)} KB in all`);
